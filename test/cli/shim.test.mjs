// The terminal shim `<home>/bin/cc-rsi` (SPEC §13.2): exact content, mode 0755, rewritten only when
// it differs, safe quoting, and it actually runs the CLI.

import assert from 'node:assert/strict'
import { lstatSync, readFileSync, symlinkSync, writeFileSync, chmodSync, mkdirSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, it } from 'node:test'
import { shimContent, writeShim } from '../../lib/cli/shim.mjs'
import { tmpDir, tmpHome } from '../_helpers/tmp.mjs'

const ROOT = resolve(fileURLToPath(new URL('../..', import.meta.url)))

describe('writeShim', () => {
  it('writes the exact shim with mode 0755 and only rewrites it when it differs', async () => {
    const { home } = await tmpHome()
    assert.equal(await writeShim(home, ROOT), true)
    const path = join(home, 'bin', 'cc-rsi')
    assert.equal(readFileSync(path, 'utf8'), [
      '#!/bin/sh',
      '# Generated by cc-rsi SessionStart; points at the plugin root of the most recent Claude Code session.',
      `exec node "${ROOT}/bin/cc-rsi" "$@"`,
      '',
    ].join('\n'))
    assert.equal(lstatSync(path).mode & 0o777, 0o755)
    assert.equal(await writeShim(home, ROOT), false, 'unchanged content is not rewritten')
    const other = await tmpDir('cc-rsi-plugin-')
    assert.equal(await writeShim(home, other), true)
    assert.match(readFileSync(path, 'utf8'), new RegExp(`exec node "${other}/bin/cc-rsi"`))
    // A wrong mode is repaired even when the content matches.
    chmodSync(path, 0o644)
    assert.equal(await writeShim(home, other), true)
    assert.equal(lstatSync(path).mode & 0o777, 0o755)
  })

  it('quotes shell metacharacters and refuses unsafe roots', async () => {
    const text = shimContent('/opt/we "ird"/$HOME/`x`/back\\slash')
    assert.match(text, /exec node "\/opt\/we \\"ird\\"\/\\\$HOME\/\\`x\\`\/back\\\\slash\/bin\/cc-rsi" "\$@"/)
    const { home } = await tmpHome()
    await assert.rejects(writeShim(home, 'relative/root'), { code: 'shim_unsafe_root' })
    await assert.rejects(writeShim(home, '/a\nb'), { code: 'shim_unsafe_root' })
    await assert.rejects(writeShim('relative-home', ROOT), { code: 'shim_unsafe_home' })
  })

  it('replaces a symlink at the shim path instead of writing through it', async () => {
    const { home } = await tmpHome()
    const victim = join(await tmpDir(), 'victim.txt')
    writeFileSync(victim, 'keep\n')
    mkdirSync(join(home, 'bin'), { recursive: true })
    symlinkSync(victim, join(home, 'bin', 'cc-rsi'))
    assert.equal(await writeShim(home, ROOT), true)
    assert.equal(readFileSync(victim, 'utf8'), 'keep\n')
    assert.equal(lstatSync(join(home, 'bin', 'cc-rsi')).isSymbolicLink(), false)
  })

  it('the shim runs the CLI', async () => {
    const { home, env } = await tmpHome()
    await writeShim(home, ROOT)
    const r = spawnSync('/bin/sh', [join(home, 'bin', 'cc-rsi'), 'version'], {
      env: { ...env, PATH: `${dirname(process.execPath)}:${env.PATH ?? ''}` }, encoding: 'utf8',
    })
    assert.equal(r.status, 0, r.stderr)
    assert.match(r.stdout, /^cc-rsi \d+\.\d+\.\d+/)
  })
})
