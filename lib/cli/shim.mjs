// The terminal shim `<home>/bin/cc-rsi` (SPEC §13.2, PR §11).
//
// `bin/` of a plugin is on the Bash tool's PATH but not on the user's terminal PATH, and the
// installed plugin root changes with every update (`~/.claude/plugins/cache/…/<sha>`). SessionStart
// therefore refreshes a small POSIX sh shim that points at the plugin root of the most recent Claude
// Code session; users put `<home>/bin` on their PATH once. Role children never see it: the child env
// strips `<home>/bin` from PATH (SPEC §10.5, J2-4).
//
// Imported by hooks/hook.mjs (SessionStart) on its hot path, so this module imports only node:* and
// lib/core (SPEC §3 import boundaries).

import { randomBytes } from 'node:crypto'
import { lstat, mkdir, open, readFile, rename, unlink } from 'node:fs/promises'
import { isAbsolute, join, resolve } from 'node:path'
import { fsyncDir } from '../core/atomic.mjs'
import { CcRsiError } from '../core/errors.mjs'
import { globalLayout } from '../core/paths.mjs'

/** Quotes `text` for use inside a POSIX sh double-quoted string. */
function shDoubleQuoted(text) {
  return text.replace(/[\\"$`]/g, ch => `\\${ch}`)
}

/** The exact shim text for `pluginRoot` (SPEC §13.2). */
export function shimContent(pluginRoot) {
  return [
    '#!/bin/sh',
    '# Generated by cc-rsi SessionStart; points at the plugin root of the most recent Claude Code session.',
    `exec node "${shDoubleQuoted(join(pluginRoot, 'bin', 'cc-rsi'))}" "$@"`,
    '',
  ].join('\n')
}

/**
 * Writes `<home>/bin/cc-rsi` (mode 0755) pointing at `<pluginRoot>/bin/cc-rsi`, only when its
 * content differs. Returns true when the shim was (re)written, false when it was already current.
 * Refuses a relative plugin root or one containing a newline or NUL (CcRsiError 'shim_unsafe_root').
 * The write is atomic (temp file, fchmod 0755, fsync, rename, fsync dir); an existing symlink at the
 * shim path is replaced, never followed.
 */
export async function writeShim(home, pluginRoot) {
  if (typeof home !== 'string' || !isAbsolute(home)) throw new CcRsiError('shim_unsafe_home', `cc-rsi home must be an absolute path (got ${JSON.stringify(home)})`)
  if (typeof pluginRoot !== 'string' || !isAbsolute(pluginRoot) || /[\n\r\0]/.test(pluginRoot)) {
    throw new CcRsiError('shim_unsafe_root', `the plugin root must be an absolute path without newlines (got ${JSON.stringify(pluginRoot)})`)
  }
  const g = globalLayout(resolve(home))
  const content = shimContent(resolve(pluginRoot))
  const info = await lstat(g.binShim).catch(() => null)
  if (info && info.isFile() && (info.mode & 0o777) === 0o755) {
    const current = await readFile(g.binShim, 'utf8').catch(() => null)
    if (current === content) return false
  }
  await mkdir(g.bin, { recursive: true, mode: 0o700 })
  const tmp = join(g.bin, `.cc-rsi.${process.pid}.${randomBytes(6).toString('hex')}.tmp`)
  let handle
  try {
    handle = await open(tmp, 'wx', 0o700)
    await handle.writeFile(content, 'utf8')
    // An explicit chmod: the open mode is filtered by the umask.
    await handle.chmod(0o755)
    await handle.sync()
    await handle.close()
    handle = undefined
    await rename(tmp, g.binShim)
  } catch (error) {
    await handle?.close().catch(() => undefined)
    await unlink(tmp).catch(() => undefined)
    throw error
  }
  await fsyncDir(g.bin)
  return true
}
